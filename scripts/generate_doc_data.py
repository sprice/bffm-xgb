def run_repo_facts(facts: Facts, check: bool) -> bool:
    """Write (or check) repo-facts.generated.ts. Returns True on success."""
    new_content = render_repo_facts_ts(facts)
    if check:
        if not REPO_FACTS_OUT.exists():
            print(f"MISSING: {REPO_FACTS_OUT.relative_to(PACKAGE_ROOT)}", file=sys.stderr)
            return False
        current = REPO_FACTS_OUT.read_text(encoding="utf-8")
        if current != new_content:
            print(
                f"STALE: {REPO_FACTS_OUT.relative_to(PACKAGE_ROOT)} "
                "is out of date; run `make gen-docs`.",
                file=sys.stderr,
            )
            return False
        print(f"ok: {REPO_FACTS_OUT.relative_to(PACKAGE_ROOT)}")
        return True
    REPO_FACTS_OUT.write_text(new_content, encoding="utf-8")
    print(f"wrote {REPO_FACTS_OUT.relative_to(PACKAGE_ROOT)}")
    return True


def run_inject(facts: Facts, check: bool) -> bool:
    """Inject (or check) GENERATED fences in the markdown targets."""
    ok = True
    for path in MARKDOWN_TARGETS:
        if not path.exists():
            continue
        current = path.read_text(encoding="utf-8")
        if "<!-- BEGIN GENERATED:" not in current:
            continue
        updated = inject_markdown(current, facts, path)
        if check:
            if updated != current:
                print(
                    f"STALE: {path.relative_to(PACKAGE_ROOT)} "
                    "has out-of-date generated blocks; run `make gen-docs`.",
                    file=sys.stderr,
                )
                ok = False
            else:
                print(f"ok: {path.relative_to(PACKAGE_ROOT)}")
        elif updated != current:
            path.write_text(updated, encoding="utf-8")
            print(f"injected {path.relative_to(PACKAGE_ROOT)}")
        else:
            print(f"unchanged {path.relative_to(PACKAGE_ROOT)}")
    return ok


def list_markdown_targets() -> list[str]:
    """Repo-relative paths of every markdown file the generator injects.

    The single source of truth for the injected-file set so the Makefile's
    check-docs git-diff guard can derive its list from here (via the
    ``list-targets`` mode) instead of hand-duplicating MARKDOWN_TARGETS, which
    would silently un-guard a file if the two lists ever drift apart.
    """
    return [str(path.relative_to(PACKAGE_ROOT)) for path in MARKDOWN_TARGETS]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "mode",
        choices=["repo-facts", "inject", "all", "list-targets"],
        help=(
            "repo-facts: emit the .ts; inject: rewrite markdown fences; "
            "all: both; list-targets: print the injected .md paths (for the "
            "check-docs git-diff guard) and exit"
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify outputs are up to date without writing (non-zero exit if stale)",
    )
    args = parser.parse_args(argv)

    if args.mode == "list-targets":
        for target in list_markdown_targets():
            print(target)
        return 0

    facts = Facts()
    ok = True
    if args.mode in ("repo-facts", "all"):
        ok = run_repo_facts(facts, args.check) and ok
    if args.mode in ("inject", "all"):
        ok = run_inject(facts, args.check) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
