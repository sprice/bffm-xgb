def _num(value: float, places: int) -> float:
    """Round to ``places`` decimals, mirroring the committed repoFacts display."""
    return round(float(value), places)


def build_repo_facts(facts: Facts) -> dict[str, Any]:
    """Assemble the reference-variant repoFacts object from artifacts."""
    ref = facts.reference
    rni = facts.rni
    sim = ref["simulation"]
    norms = rni["norms"]["norms"]
    rbar = rni["reliability"]["full_50"]
    db20 = facts.mva("domain_balanced", 20)
    mi20 = facts.mva("mini_ipip", 20)
    selected = facts.first_item_selected

    # Cross-check that every domain shares the same mean_items_used before
    # presenting it as a single global per-domain mean (and 5x-ing it for the
    # total). Mirrors the n_valid / augmentation-counts cross-checks so an
    # unequal future simulation fails loudly instead of silently using 'ext'.
    per_domain_items = [
        float(sim["domain_metrics"][dom]["mean_items_used"]) for dom in DOMAIN_ORDER
    ]
    mean_items_per_domain = per_domain_items[0]
    if any(v != mean_items_per_domain for v in per_domain_items):
        raise ValueError(
            "simulation mean_items_used differs across domains "
            f"(per-domain {dict(zip(DOMAIN_ORDER, per_domain_items, strict=True))}); "
            "meanItemsPerDomain assumes one shared global mean"
        )

    # K=20 unconstrained greedy adaptive_topk per-domain item allocation: the
    # exact correlation-ranking result that produces domain starvation (ch10's
    # greedy-failure barList). Sourced so it can never silently desync on a re-run.
    greedy_topk20 = rni["baseline_comparison_results"]["per_domain"]["20"]["adaptive_topk"]

    return {
        "totalValidRespondents": facts.n_valid,
        "trainRows": facts.train_rows,
        "valRows": facts.val_rows,
        "testRows": facts.test_rows,
        "firstItemId": str(selected["id"]),
        "firstItemText": str(selected["text"]),
        "firstItemCrossDomainInfo": _num(selected["cross_domain_info"], 4),
        "splitScheme": facts.split_scheme,
        "baselineK20": {
            "domainBalancedR": _num(ref["baselines"]["k20"]["domain_balanced"]["pearson_r"], 4),
            "domainBalancedMae": _num(ref["baselines"]["k20"]["domain_balanced"]["mae"], 2),
            "miniIpipStandaloneR": _num(ref["baselines"]["k20"]["mini_ipip"]["pearson_r"], 4),
            "adaptiveTopKR": _num(ref["baselines"]["k20"]["adaptive_topk"]["pearson_r"], 4),
            "constrainedAdaptiveR": _num(
                ref["baselines"]["k20"]["domain_constrained_adaptive"]["pearson_r"], 4
            ),
        },
        "mlVsAveragingK20": {
            "domainBalanced": {
                "mlR": _num(db20["ml_r"], 4),
                "avgR": _num(db20["avg_r"], 4),
                "deltaR": _num(db20["delta_r"], 4),
            },
            "miniIpip": {
                "mlR": _num(mi20["ml_r"], 4),
                "avgR": _num(mi20["avg_r"], 4),
                "deltaR": _num(mi20["delta_r"], 4),
            },
        },
        "validation": {
            "full50R": _num(ref["validation"]["full_50"]["pearson_r"], 4),
            "full50Mae": _num(ref["validation"]["full_50"]["mae"], 2),
            "full50Coverage": _num(ref["validation"]["full_50"]["coverage_90"], 4),
            "sparse20R": _num(ref["validation"]["sparse_20"]["pearson_r"], 4),
            "sparse20Mae": _num(ref["validation"]["sparse_20"]["mae"], 2),
            "sparse20Coverage": _num(ref["validation"]["sparse_20"]["coverage_90"], 4),
        },
        "simulation": {
            "overallR": _num(sim["overall"]["pearson_r"], 4),
            "overallMae": _num(sim["overall"]["mae"], 2),
            "overallCoverage": _num(sim["overall"]["coverage_90"], 4),
            "meanItemsPerDomain": _int_or_float(mean_items_per_domain),
            "meanItemsTotal": _int_or_float(5 * mean_items_per_domain),
        },
        "norms": {
            dom: {
                "mean": _num(norms[dom]["mean"], 4),
                "sd": _num(norms[dom]["sd"], 4),
            }
            for dom in DOMAIN_ORDER
        },
        "interItemRBar": {dom: _num(rbar[dom]["r_bar"], 4) for dom in DOMAIN_ORDER},
        "greedyTopK20ItemsPerDomain": {
            dom: int(greedy_topk20[dom]["n_domain_items"]) for dom in DOMAIN_ORDER
        },
        "currentLockedParams": dict(facts.tuned_params["hyperparameters"]),
    }


def _int_or_float(value: float) -> int | float:
    """Render whole numbers as ints (4.0 -> 4) so they round-trip cleanly."""
    fvalue = float(value)
    return int(fvalue) if fvalue.is_integer() else fvalue


def _ts_value(value: Any, indent: int) -> str:
    pad = "  " * indent
    inner = "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = ["{"]
        for key, val in value.items():
            lines.append(f"{inner}{_ts_key(key)}: {_ts_value(val, indent + 1)},")
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        # repr keeps the full float precision (e.g. learning_rate) and emits a
        # decimal point so TS sees a number literal.
        return repr(value)
    raise TypeError(f"unsupported repoFacts value type: {type(value)!r}")


_TS_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _ts_key(key: str) -> str:
    return key if _TS_IDENT.match(key) else json.dumps(key)


def render_repo_facts_ts(facts: Facts) -> str:
    obj = build_repo_facts(facts)
    body = _ts_value(obj, 0)
    return f"{GENERATED_HEADER}\nexport const repoFacts = {body} as const;\n"


