#!/usr/bin/env python3
"""Generate doc data from the reference source-of-truth artifacts.

Single source of truth: ``artifacts/research_summary.json`` (variant-aware;
reference data under ``reference_notes_inputs`` plus ``variants.reference``)
together with the force-tracked metadata artifacts
(``data/processed/load_metadata.json``,
``data/processed/canonical_v1/{split_metadata,first_item}.json``,
``artifacts/tuned_params.json``, ``artifacts/ipip_bffm_norms.json``).

Every model-derived value shown in a doc must be GENERATED from these
artifacts, never hand-typed. Pure design constants that can never change
between runs (5 domains, 1-5 Likert scale, tau=0.05/0.50/0.95, item counts
like 50/20/4) stay inline in the prose.

Two modes:

``repo-facts``
    Emit ``web/src/client/learn/content/repo-facts.generated.ts`` --
    an ``export const repoFacts = {...} as const;`` built from the
    reference artifacts. ``data.ts`` re-exports it (MECHANISM 1).

``inject``
    Scan a configured set of ``.md`` files for fenced blocks
    ``<!-- BEGIN GENERATED: <key> -->`` ... ``<!-- END GENERATED: <key> -->``
    and replace the inner content with the rendered block for ``<key>``
    (MECHANISM 2). Prose OUTSIDE the fences stays hand-edited.

Usage::

    uv run python scripts/generate_doc_data.py repo-facts
    uv run python scripts/generate_doc_data.py inject
    uv run python scripts/generate_doc_data.py repo-facts --check   # diff only
    uv run python scripts/generate_doc_data.py inject --check
    uv run python scripts/generate_doc_data.py all                  # both modes
"""

