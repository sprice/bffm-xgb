_CONFLICT_MARKER_RE = re.compile(r"^(<<<<<<< |=======$|>>>>>>> )", re.MULTILINE)


def _load_json(path: Path) -> dict[str, Any]:
    """Load a source artifact, re-raising a clear, actionable diagnostic.

    A bare FileNotFoundError/JSONDecodeError traceback does not name the
    offending artifact or the remedy, and an unresolved merge conflict in a
    source artifact surfaces as an opaque json decoder error. Name the path,
    detect conflict markers, and point at ``make gen-docs``.
    """
    try:
        raw = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        rel = path.relative_to(PACKAGE_ROOT) if path.is_relative_to(PACKAGE_ROOT) else path
        raise FileNotFoundError(
            f"missing source artifact: {rel}. Regenerate the artifacts and run "
            "`make gen-docs` (the doc generator reads only committed/force-tracked "
            "source-of-truth artifacts)."
        ) from exc
    if _CONFLICT_MARKER_RE.search(raw):
        rel = path.relative_to(PACKAGE_ROOT) if path.is_relative_to(PACKAGE_ROOT) else path
        raise ValueError(
            f"unresolved merge conflict in {rel}: it contains git conflict markers "
            "(<<<<<<< / ======= / >>>>>>>). Resolve the conflict (or rerun "
            "`make gen-docs` to regenerate it) before generating docs."
        )
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        rel = path.relative_to(PACKAGE_ROOT) if path.is_relative_to(PACKAGE_ROOT) else path
        raise ValueError(
            f"malformed JSON in source artifact {rel} "
            f"(line {exc.lineno}, column {exc.colno}): {exc.msg}. "
            "Regenerate it and run `make gen-docs`."
        ) from exc


class Facts:
    """Parsed reference-variant facts pulled from the artifacts.

    All accessors read ONLY the source-of-truth artifacts named in the
    architecture; nothing is hand-typed.
    """

    def __init__(self) -> None:
        self.summary = _load_json(RESEARCH_SUMMARY_PATH)
        self.load_metadata = _load_json(LOAD_METADATA_PATH)
        self.split_metadata = _load_json(SPLIT_METADATA_PATH)
        self.first_item = _load_json(FIRST_ITEM_PATH)
        self.tuned_params = _load_json(TUNED_PARAMS_PATH)
        self.norms_artifact = _load_json(NORMS_PATH)

        self.rni: dict[str, Any] = self.summary["reference_notes_inputs"]
        self.reference: dict[str, Any] = self.summary["variants"]["reference"]

        # ml_vs_averaging comparisons indexed by (method, n_items).
        self._mva: dict[tuple[str, int], dict[str, Any]] = {
            (row["method"], row["n_items"]): row
            for row in self.rni["ml_vs_averaging_comparison"]["comparisons"]
        }

        self._assert_deployed_coverage_consistent()

    # Genuine semantic tolerance between the two 'deployed 20-item form' coverage
    # operating points (~1 pct point). They are *distinct* operating points, so
    # exact .1f%-display equality is too tight: today they are 89.52% vs 89.47%
    # and round equal only by landing in the same display bucket. A retrain that
    # nudges either across a rounding boundary must not hard-fail all doc
    # generation when each number is individually correct -- only a real
    # divergence (~1 pct point) should.
    _DEPLOYED_COVERAGE_TOL = 0.01

    def _assert_deployed_coverage_consistent(self) -> None:
        """Fail loudly if the two 'deployed 20-item form' coverage sources diverge.

        ``comparison-table`` labels the fixed-mask K=20 domain-balanced baseline
        (``baselines.k20.domain_balanced.coverage_90``) as the deployed form,
        while ``coverage-by-regime`` labels the SEM-stopped adaptive simulation
        (``simulation_results.analysis.overall_metrics.coverage_90``) as the same
        deployed form. They are semantically distinct operating points but both
        carry the "deployed 20-item form" prose. There is no shared constant
        tying them together, so a refresh could make them genuinely disagree
        while both prose blocks still claim the deployed form. Assert they agree
        to a real semantic tolerance (``_DEPLOYED_COVERAGE_TOL``, ~1 pct point)
        -- NOT exact .1f%-display equality, which a benign post-retrain rounding
        straddle could trip even though each number is individually correct.
        """
        fixed = float(self.reference["baselines"]["k20"]["domain_balanced"]["coverage_90"])
        adaptive = float(
            self.rni["simulation_results"]["analysis"]["overall_metrics"]["coverage_90"]
        )
        if abs(fixed - adaptive) >= self._DEPLOYED_COVERAGE_TOL:
            raise ValueError(
                "'deployed 20-item form' coverage diverges beyond the semantic "
                f"tolerance ({self._DEPLOYED_COVERAGE_TOL * 100:.1f} pct points) "
                f"between baselines.k20.domain_balanced ({fixed:.4f} -> "
                f"{fixed * 100:.1f}%) and simulation_results overall_metrics "
                f"({adaptive:.4f} -> {adaptive * 100:.1f}%); comparison-table and "
                "coverage-by-regime both label this the deployed form. Reconcile "
                "the artifacts or relabel one regime before regenerating docs."
            )

    def mva(self, method: str, n_items: int) -> dict[str, Any]:
        return self._mva[(method, n_items)]

    # -- data counts ------------------------------------------------------- #
    @property
    def n_valid(self) -> int:
        n_valid = int(self.load_metadata["row_counts"]["n_valid"])
        # Cross-check against split_metadata.total_valid so a desync fails loudly.
        if n_valid != int(self.split_metadata["total_valid"]):
            raise ValueError(
                "load_metadata.n_valid != split_metadata.total_valid: "
                f"{n_valid} != {self.split_metadata['total_valid']}"
            )
        return n_valid

    @property
    def train_rows(self) -> int:
        return int(self.split_metadata["train_rows"])

    @property
    def val_rows(self) -> int:
        return int(self.split_metadata["val_rows"])

    @property
    def test_rows(self) -> int:
        return int(self.split_metadata["test_rows"])

    @property
    def split_scheme(self) -> str:
        return str(self.split_metadata["split_scheme"])

    @property
    def split_id(self) -> str:
        return str(self.split_metadata["split_id"])

    @property
    def seed(self) -> int:
        return int(self.split_metadata["seed"])

    @property
    def train_frac(self) -> float:
        return float(self.split_metadata["train_frac"])

    @property
    def val_frac(self) -> float:
        return float(self.split_metadata["val_frac"])

    @property
    def test_frac(self) -> float:
        return float(self.split_metadata["test_frac"])

    # -- first item -------------------------------------------------------- #
    @property
    def first_item_selected(self) -> dict[str, Any]:
        return self.first_item["selected_item"]


