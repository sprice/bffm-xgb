def _fmt_r3(value: float) -> str:
    """Pearson r in leading-dot 3-decimal style (0.928 -> '.928', -0.05 -> '-.050').

    Strip only the leading zero of the magnitude, preserving any sign. A plain
    ``lstrip("0")`` is a no-op on a negative value (the string starts with '-'),
    rendering '-0.050' next to leading-dot '.928' siblings -- an inconsistency a
    sub-zero ablation correlation would surface in the comparison/per-domain
    tables. ``re.sub`` collapses both the positive and negative cases uniformly
    and never widens the cell.
    """
    return re.sub(r"^(-?)0\.", r"\1.", f"{value:.3f}")


def _cell(content: str, inner_width: int) -> str:
    """Render a Markdown cell body ' content...' padded to ``inner_width`` chars.

    The committed README tables use fixed (slightly irregular) inner-cell widths;
    reproducing them byte-for-byte keeps the injected diff to numbers only.
    """
    body = f" {content}"
    if len(body) > inner_width:
        raise ValueError(f"cell {content!r} exceeds width {inner_width}")
    return body + " " * (inner_width - len(body))


def render_comparison_table(facts: Facts) -> str:
    """Mini-IPIP (averaging) vs BFFM-XGB-20 (XGBoost) headline table."""
    db20 = facts.mva("domain_balanced", 20)
    mi20 = facts.mva("mini_ipip", 20)
    coverage = facts.reference["baselines"]["k20"]["domain_balanced"]["coverage_90"]

    overall_mini = _fmt_r3(mi20["avg_r"])
    overall_xgb = _fmt_r3(db20["ml_r"])
    mae_mini = f"{mi20['avg_mae']:.1f}"
    mae_xgb = f"{db20['ml_mae']:.1f}"
    cov_pct = f"{coverage * 100:.1f}"

    # Fixed inner-cell widths matching the committed table (col1=30, col2=24, col3=29).
    rows = [
        "|                              | Mini-IPIP (averaging)  | BFFM-XGB-20 (XGBoost)       |",
        "| ---------------------------- | ---------------------- | --------------------------- |",
        "| **Items**                    | 20 (4 per domain)      | 20 (4 per domain)           |",
        "| **Item selection**           | Expert-curated brevity | Top-4 by within-domain *r*  |",
        "| **Scoring**                  | Simple scale averaging | XGBoost quantile regression |",
        f"|{_cell('**Overall *r***', 30)}|{_cell(overall_mini, 24)}|{_cell(f'**{overall_xgb}**', 29)}|",
        f"|{_cell('**MAE (percentile pts)**', 30)}|{_cell(mae_mini, 24)}|{_cell(f'**{mae_xgb}**', 29)}|",
        f"|{_cell('**90% prediction intervals**', 30)}|{_cell('—', 24)}|{_cell(f'✓ ({cov_pct}% coverage)', 29)}|",
    ]
    return "\n".join(rows)


def render_per_domain_k20(facts: Facts) -> str:
    """Per-domain accuracy at K=20: Mini-IPIP averaging r vs BFFM-XGB-20 r.

    The Mini-IPIP *alpha* column is a hand-cited published Donnellan et al.
    (2006) literature constant (NOT artifact-derived); it is carried through
    verbatim so the generated table matches the committed prose.
    """
    db20 = facts.mva("domain_balanced", 20)
    mi20 = facts.mva("mini_ipip", 20)

    # Hand-cited published reliabilities (literature constant, not this sample).
    published_alpha = {
        "ext": ".77",
        "agr": ".70",
        "csn": ".69",
        "est": ".68",
        "opn": ".65",
    }

    header = [
        "| Domain                | Mini-IPIP *α* (reported) | Mini-IPIP *r* (averaging) | BFFM-XGB-20 *r* (XGBoost) |",
        "| --------------------- | ------------------------ | ------------------------- | ------------------------- |",
    ]
    rows: list[str] = []
    # Fixed inner-cell widths matching the committed table (col1=23, col2=26, col3=15, col4=17).
    for dom in DOMAIN_ORDER:
        label = DOMAIN_LABELS[dom]
        alpha = published_alpha[dom]
        mini = _fmt_r3(mi20["avg_per_domain"][dom])
        xgb = _fmt_r3(db20["ml_per_domain"][dom])
        rows.append(
            f"|{_cell(label, 23)}|{_cell(alpha, 26)}|{_cell(mini, 15)}|{_cell(f'**{xgb}**', 17)}|"
        )
    return "\n".join(header + rows)


